/**
 * The investigation: an LLM's (or the mock's) interpretation of the stored facts.
 * Everything here is inferred, so it is styled as such (docs/design-system.md,
 * "Investigation panel"). Nothing on this panel acts on anything: remediation is text.
 */
import { ApiError } from '../../api/client';
import type { Incident, InvestigationResult } from '../../api/types';
import { Button } from '../../components/Button';
import {
  capitalize,
  formatDurationMs,
  formatRelative,
  formatUtc,
  formatUtcFull,
  plural,
} from '../../lib/format';
import { useNow } from '../../lib/useNow';
import { useElapsedSeconds } from '../sync/api';
import { useSystem } from '../system/api';
import { useInvestigation, useRunInvestigation } from './api';
import styles from './InvestigationPanel.module.css';

function Citations({ ids }: { ids: string[] }) {
  return (
    <span className={styles.cites} aria-label="Cites">
      {ids.map((id) => (
        <a key={id} href={`#fact-${id}`} className="mono">
          {id}
        </a>
      ))}
    </span>
  );
}

function Findings({ result, now }: { result: InvestigationResult; now: number }) {
  const inv = result.investigation;
  const findings = inv.findings;
  if (!findings) return null;
  return (
    <>
      {inv.provider === 'mock' && (
        <p className={styles.mock} role="note">
          Mock provider: generated by fixed rules, not a language model.
        </p>
      )}
      <p className={styles.summary}>{findings.summary}</p>

      <section aria-label="Hypotheses" className={styles.group}>
        <h4 className={styles.h4}>Hypotheses</h4>
        <ol className={styles.list}>
          {findings.hypotheses.map((h) => (
            <li key={h.id} className={styles.inferred}>
              <span className={`mono ${styles.id}`}>{h.id}</span>
              <div>
                <p>{h.statement}</p>
                <p className={styles.meta}>
                  <span>Confidence: {h.confidence}</span>
                  <Citations ids={h.cites} />
                </p>
              </div>
            </li>
          ))}
        </ol>
      </section>

      {findings.next_checks && findings.next_checks.length > 0 && (
        <section aria-label="Next checks" className={styles.group}>
          <h4 className={styles.h4}>Next checks</h4>
          <ol className={styles.list}>
            {findings.next_checks.map((c) => (
              <li key={c.id} className={styles.inferred}>
                <span className={`mono ${styles.id}`}>{c.id}</span>
                <div>
                  <p>{c.description}</p>
                  <p className={styles.meta}>
                    <Citations ids={c.cites} />
                  </p>
                </div>
              </li>
            ))}
          </ol>
        </section>
      )}

      {findings.remediation && findings.remediation.length > 0 && (
        <section aria-label="Remediation" className={styles.group}>
          <h4 className={styles.h4}>Remediation</h4>
          <ol className={styles.list}>
            {findings.remediation.map((r) => (
              <li key={r.id} className={styles.inferred}>
                <span className={`mono ${styles.id}`}>{r.id}</span>
                <div>
                  <p>
                    <span className={styles.human}>Human decision</span> {r.description}
                  </p>
                  <p className={styles.meta}>
                    <Citations ids={r.cites} />
                  </p>
                </div>
              </li>
            ))}
          </ol>
        </section>
      )}

      {findings.limitations && findings.limitations.length > 0 && (
        <section aria-label="Limitations" className={styles.group}>
          <h4 className={styles.h4}>Limitations</h4>
          <ul className={styles.limitations}>
            {findings.limitations.map((l, i) => (
              <li key={i}>{l}</li>
            ))}
          </ul>
        </section>
      )}
      <RunDetails result={result} now={now} />
    </>
  );
}

function RunDetails({ result, now }: { result: InvestigationResult; now: number }) {
  const inv = result.investigation;
  const duration = new Date(inv.finished_at).getTime() - new Date(inv.started_at).getTime();
  return (
    <dl className={styles.details}>
      <div>
        <dt>Provider</dt>
        <dd className="mono">
          {inv.provider} {inv.model}
        </dd>
      </div>
      <div>
        <dt>Ran</dt>
        <dd title={formatUtcFull(inv.finished_at)}>
          <span className="mono">{formatUtc(inv.finished_at)}</span>{' '}
          {formatRelative(inv.finished_at, now)}
        </dd>
      </div>
      <div>
        <dt>Duration</dt>
        <dd className="mono">{formatDurationMs(duration)}</dd>
      </div>
      <div>
        <dt>Attempts</dt>
        <dd className="mono">{inv.attempts}</dd>
      </div>
      <div>
        <dt>Runs</dt>
        <dd className="mono">{result.runs}</dd>
      </div>
      <div>
        <dt>Evidence used</dt>
        <dd className="mono">{inv.evidence_hash}</dd>
      </div>
    </dl>
  );
}

export function InvestigationPanel({ incident }: { incident: Incident }) {
  const saved = useInvestigation(incident.id);
  const run = useRunInvestigation(incident.id);
  const system = useSystem();
  const elapsed = useElapsedSeconds(run.isPending);
  const now = useNow();

  const llm = system.data?.llm;
  const providerLabel =
    llm?.provider === 'mock' ? 'the mock provider' : (llm?.provider ?? 'the provider');
  const result = saved.data ?? null;
  const unavailable = llm !== undefined && !llm.configured;

  const runButton = (label: string) => (
    <Button onClick={() => run.mutate()} disabled={run.isPending || unavailable}>
      {run.isPending ? `Investigating… ${elapsed} s` : label}
    </Button>
  );

  let body;
  if (saved.isPending) {
    body = (
      <div aria-busy="true" aria-label="Loading investigation">
        <div className={styles.skeleton} />
        <div className={styles.skeleton} />
      </div>
    );
  } else if (saved.isError && !result) {
    body = (
      <p className={styles.error} role="alert">
        Could not load the investigation: {saved.error.message}
      </p>
    );
  } else if (!result) {
    body = unavailable ? (
      <div className={styles.state}>
        <p className={styles.stateTitle}>Investigation unavailable.</p>
        <p className={styles.stateDetail}>
          The {llm?.provider} provider is not configured. Set SENTINEL_LLM_BASE_URL and
          SENTINEL_LLM_MODEL, or use the mock.
        </p>
      </div>
    ) : (
      <div className={styles.state}>
        <p className={styles.stateTitle}>No investigation yet.</p>
        <p className={styles.stateDetail}>
          Sends this incident&apos;s {plural(incident.facts.length, 'fact')} to {providerLabel} and
          checks that every hypothesis cites them. The incident itself is not changed.
        </p>
        {runButton('Run investigation')}
      </div>
    );
  } else {
    const inv = result.investigation;
    body = (
      <>
        {result.outdated && (
          <p className={styles.outdated} role="status">
            This investigation used older evidence. The incident has changed since it ran.
          </p>
        )}
        {inv.status === 'failed' && inv.error ? (
          <div className={`${styles.state} ${styles.failed}`} role="alert">
            <p className={styles.stateTitle}>Investigation failed.</p>
            <p className={styles.stateDetail}>{inv.error.message}</p>
            {inv.error.hint && <p className={styles.stateDetail}>{inv.error.hint}</p>}
            <p className={`mono ${styles.code}`}>{inv.error.code}</p>
            <RunDetails result={result} now={now} />
          </div>
        ) : (
          <Findings result={result} now={now} />
        )}
        <div className={styles.actions}>{runButton('Run again')}</div>
      </>
    );
  }

  return (
    <section aria-labelledby="investigation-title" className={styles.panel}>
      <h2 id="investigation-title" className={styles.h2}>
        <span>Investigation</span>
        <span className={styles.inferredTag}>Inferred</span>
        {llm && (
          <span className={styles.provider}>
            {capitalize(llm.provider ?? 'none')}
            {llm.model ? ` ${llm.model}` : ''}
          </span>
        )}
      </h2>
      {body}
      {run.isError && (
        <p className={styles.error} role="alert">
          {run.error instanceof ApiError ? run.error.message : 'The investigation request failed.'}
          {run.error instanceof ApiError && run.error.hint ? ` ${run.error.hint}` : ''}
        </p>
      )}
    </section>
  );
}
