"""MockProvider: the default. Deterministic, no network, no API key.

It is not a language model. It reads the evidence block of the prompt and fills the reply
schema with fixed templates that cite real fact ids, so the whole investigation path
(prompt, validation, storage, UI) works and can be demonstrated without any provider.
The console labels its output as generated by rules.
"""

import json
from typing import Any

from sentinel.investigation.prompt import evidence_from_prompt

BREACH_KINDS = ("threshold_breach", "baseline_deviation")

# One plain-language reading per rule. Templates, not inference.
RULE_HYPOTHESES: dict[str, tuple[str, str, str]] = {
    # rule: (hypothesis, next check, remediation)
    "R-CPU-SAT": (
        "Sustained workload demand is exceeding the instance's CPU capacity.",
        "Identify which processes consume the CPU during the breach window.",
        "Consider reducing the load or moving to a larger instance type after review.",
    ),
    "R-CPU-CREDIT": (
        "CPU usage above the burstable baseline drained the credit balance; the instance "
        "is now throttled to its baseline performance.",
        "Check how long CPU usage stayed above the instance's baseline before credits ran out.",
        "Consider unlimited credit mode or a non-burstable instance type after a cost review.",
    ),
    "R-MEM": (
        "Memory use grew beyond what the instance can sustain: possible leak or higher load.",
        "Check whether memory grew steadily (leak) or stepped up with traffic.",
        "Consider restarting the affected process during a maintenance window after review.",
    ),
    "R-STATUS": (
        "The instance or its host is impaired: the EC2 status check is failing.",
        "Check whether the instance or the system status check is the one failing.",
        "Consider stopping and starting the instance to move it to healthy hardware.",
    ),
    "R-5XX": (
        "The application is returning server errors for a share of requests.",
        "Check application error logs for the most frequent error around the breach start.",
        "Consider rolling back the most recent change if errors started after it.",
    ),
    "R-LAT": (
        "Requests are much slower than this service's own baseline.",
        "Check whether slow requests share an endpoint or a downstream dependency.",
        "Consider shedding load or scaling out after confirming the slowdown's cause.",
    ),
}


def _findings(bundle: dict[str, Any]) -> dict[str, Any]:
    facts = bundle["facts"]
    breaches = [f for f in facts if f["kind"] in BREACH_KINDS]
    events = [f for f in facts if f["kind"] == "event"]
    gaps = [f for f in facts if f["kind"] == "data_gap"]

    hypotheses: list[dict[str, Any]] = []
    checks: list[dict[str, Any]] = []
    remediation: list[dict[str, Any]] = []

    first_breach = min(breaches, key=lambda f: f["window"]["start"]) if breaches else None
    # Only a change recorded before the first breach started can be a candidate cause.
    earlier = [
        e for e in events if first_breach and e["observed_at"] <= first_breach["window"]["start"]
    ]
    if first_breach and earlier:
        deploy = max(earlier, key=lambda f: f["observed_at"])
        hypotheses.append(
            {
                "statement": "A change deployed before the breach may have caused it: the "
                "deployment is the most recent recorded change on this resource.",
                "confidence": "medium",
                "cites": [deploy["id"], first_breach["id"]],
            }
        )
    for breach in breaches:
        template = RULE_HYPOTHESES.get(breach["rule_id"] or "")
        if template is None:
            continue
        hypothesis, check, fix = template
        hypotheses.append({"statement": hypothesis, "confidence": "low", "cites": [breach["id"]]})
        checks.append({"description": check, "cites": [breach["id"]]})
        remediation.append({"description": fix, "requires_human": True, "cites": [breach["id"]]})
    for gap in gaps:
        checks.append(
            {
                "description": "Restore the missing data source before trusting conclusions "
                f"about {gap['rule_id']}.",
                "cites": [gap["id"]],
            }
        )

    limitations = ["Generated by the mock provider from fixed rules, not by a language model."]
    if gaps:
        limitations.append(f"{len(gaps)} rule(s) could not be evaluated because of data gaps.")

    rules = ", ".join(bundle["incident"]["rule_ids"])
    return {
        "summary": f"{len(breaches)} breach fact(s) from {rules}; "
        f"{len(events)} recorded change(s) in the evidence window.",
        "hypotheses": [{"id": f"H{i}", **h} for i, h in enumerate(hypotheses[:5], 1)],
        "next_checks": [{"id": f"C{i}", **c} for i, c in enumerate(checks[:5], 1)],
        "remediation": [{"id": f"R{i}", **r} for i, r in enumerate(remediation[:5], 1)],
        "limitations": limitations,
    }


class MockProvider:
    name = "mock"
    model = "mock-rules-v1"

    def complete(self, prompt: str) -> str:
        bundle = json.loads(evidence_from_prompt(prompt))
        return json.dumps(_findings(bundle))
